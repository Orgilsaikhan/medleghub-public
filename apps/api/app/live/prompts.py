@dataclass(frozen=True)
class TopicLine:
    key: str
    title: str


def topic_list(topics: Sequence[TopicLine]) -> str:
    return "\n".join(f"- {topic.key} — {topic.title}" for topic in topics) or "- (сэдэвгүй)"


def pages_label(pages: Sequence[int]) -> str:
    return ", ".join(str(page) for page in pages) if pages else "тодорхойгүй"
